/**
 * الدالة الرئيسية التي تولد درساً متكاملاً وغنياً فورياً لأي درس في المنهاج الجزائري
 * لا تتطلب أي انتظار من المستخدم، وتوفر تجربة فورية 100%
 */
export function generateInstantLessonArticle(
  levelName: string,
  yearName: string,
  subjectName: string,
  lessonTitle: string,
  trackName?: string,
  semester?: number
): string {
  const category = getSubjectCategory(subjectName);
  const props: SubjectTemplateProps = {
    levelName,
    yearName,
    subjectName,
    lessonTitle,
    trackName,
    semester
  };

  switch (category) {
    case 'math':
      return generateMathLesson(props);
    case 'physics':
      return generatePhysicsLesson(props);
    case 'science':
      return generateScienceLesson(props);
    case 'arabic':
      return generateArabicLesson(props);
    case 'islamic':
      return generateIslamicLesson(props);
    case 'history':
      return generateHistoryLesson(props);
    case 'philosophy':
      return generatePhilosophyLesson(props);
    case 'french':
    case 'english':
      return generateForeignLanguageLesson(props);
    case 'civic':
      return generateCivicLesson(props);
    default:
      return generateCivicLesson(props);
  }
}

