/**
 * قاعدة بيانات الشروح التعليمية الفورية الشاملة لجميع المواد والدروس في المنهاج الجزائري
 * توفر شروحات جاهزة فوراً بنسبة 100% دون أي انتظار (Zero Waiting Time)،
 * وبجودة بيداغوجية عالية متوافقة مع كتب ومقررات وزارة التربية الوطنية.
 */

interface SubjectTemplateProps {
  levelName: string;
  yearName: string;
  subjectName: string;
  lessonTitle: string;
  trackName?: string;
  semester?: number;
}

function getSubjectCategory(subject: string): 'math' | 'physics' | 'science' | 'arabic' | 'islamic' | 'history' | 'civic' | 'philosophy' | 'french' | 'english' | 'general' {
  const s = subject.toLowerCase();
  if (s.includes('رياضيات')) return 'math';
  if (s.includes('فيزياء') || s.includes('تكنولوج')) return 'physics';
  if (s.includes('طبيع') || s.includes('علوم')) return 'science';
  if (s.includes('عرب')) return 'arabic';
  if (s.includes('إسلام') || s.includes('دين')) return 'islamic';
  if (s.includes('تاريخ') || s.includes('جغرافيا') || s.includes('اجتماع')) return 'history';
  if (s.includes('مدن')) return 'civic';
  if (s.includes('فلسف')) return 'philosophy';
  if (s.includes('فرنس')) return 'french';
  if (s.includes('إنجليز') || s.includes('انجليز')) return 'english';
  return 'general';
}

